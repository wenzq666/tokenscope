[CmdletBinding()]
param(
    [string]$InputDirectory,
    [string]$RetrievedAt = '2026-10-09',
    [switch]$Download
)
$ErrorActionPreference = 'Stop'
$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if (-not $InputDirectory) { $InputDirectory = Join-Path $repo 'build/reference-pricing' }
New-Item -ItemType Directory -Force -Path $InputDirectory | Out-Null
$feeds = [ordered]@{
    'litellm.json' = 'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json'
    'models-dev.json' = 'https://models.dev/api.json'
}
if ($Download) {
    foreach ($name in $feeds.Keys) { Invoke-WebRequest -Uri $feeds[$name] -OutFile (Join-Path $InputDirectory $name) }
    Invoke-WebRequest 'https://raw.githubusercontent.com/BerriAI/litellm/main/LICENSE' -OutFile (Join-Path $InputDirectory 'LICENSE.litellm')
    Invoke-WebRequest 'https://raw.githubusercontent.com/anomalyco/models.dev/dev/LICENSE' -OutFile (Join-Path $InputDirectory 'LICENSE.models-dev')
}
# Offline reference contains first-party text/code models and common hosted endpoints.
# The runtime parser can load the complete public feeds on demand.
$liteProviders = @('openai','anthropic','gemini','deepseek','moonshot','moonshotai','minimax','zai','z_ai',
    'xai','mistral','dashscope','qwen_ai_platform','cohere','perplexity','inception','cursor','xiaomi','stepfun','longcat')
$devProviders = @('openai','anthropic','google','deepseek','moonshotai','moonshotai-cn','minimax','minimax-cn',
    'zai','zhipuai','alibaba','alibaba-cn','xai','mistral','cohere','perplexity','inception','xiaomi','stepfun',
    'longcat','openrouter','azure','azure-cognitive-services','amazon-bedrock','google-vertex','google-vertex-anthropic',
    'siliconflow','siliconflow-cn','volcengine','tencent-tokenhub','groq','fireworks-ai','togetherai','novita-ai','opencode','cursor')
$liteRaw = Get-Content -LiteralPath (Join-Path $InputDirectory 'litellm.json') -Raw | ConvertFrom-Json -AsHashtable
$devRaw = Get-Content -LiteralPath (Join-Path $InputDirectory 'models-dev.json') -Raw | ConvertFrom-Json -AsHashtable
$lite = [ordered]@{}
foreach ($key in ($liteRaw.Keys | Sort-Object -CaseSensitive)) {
    $v = $liteRaw[$key]
    if ($v -isnot [System.Collections.IDictionary] -or $v.litellm_provider -notin $liteProviders) { continue }
    if ($v.mode -and $v.mode -notin @('chat','completion')) { continue }
    $row = [ordered]@{ litellm_provider = $v.litellm_provider; mode = 'chat' }
    foreach ($field in ($v.Keys | Sort-Object -CaseSensitive)) {
        if ($field -match '^(input_cost_per_token|output_cost_per_token|reasoning_cost_per_token|cache_read_input_token_cost|cache_creation_input_token_cost)(_above_(128k|200k|256k|272k)_tokens|_above_1hr)?$') { $row[$field] = $v[$field] }
    }
    if ($row.Count -gt 2) { $lite[$key] = $row }
}
$dev = [ordered]@{}
foreach ($provider in ($devRaw.Keys | Sort-Object -CaseSensitive)) {
    if ($provider -notin $devProviders) { continue }
    $models = [ordered]@{}
    foreach ($key in ($devRaw[$provider].models.Keys | Sort-Object -CaseSensitive)) {
        $v = $devRaw[$provider].models[$key]
        if ($null -eq $v.cost -or ($null -eq $v.cost.input -and $null -eq $v.cost.output)) { continue }
        $models[$key] = [ordered]@{ id = $v.id; cost = $v.cost }
    }
    if ($models.Count -gt 0) { $dev[$provider] = [ordered]@{ models = $models } }
}
$liteJson = $lite | ConvertTo-Json -Depth 30 -Compress
$devJson = $dev | ConvertTo-Json -Depth 30 -Compress
function Split-Literals([string]$Name,[string]$Json) {
    $pieces = [Collections.Generic.List[string]]::new()
    for ($start=0; $start -lt $Json.Length; $start+=30000) {
        $chunk=$Json.Substring($start,[Math]::Min(30000,$Json.Length-$start))
        if ($chunk.Contains(')PRICE_DATA"')) { throw 'Unexpected raw C++ string delimiter in dataset.' }
        $pieces.Add('R"PRICE_DATA('+$chunk+')PRICE_DATA"')
    }
    return 'static constexpr const char* '+$Name+'[] = {'+[Environment]::NewLine+($pieces -join (','+[Environment]::NewLine))+[Environment]::NewLine+'};'
}
$liteLiteral = Split-Literals 'kBundledLiteLLM' $liteJson
$devLiteral = Split-Literals 'kBundledModelsDev' $devJson
$content = @"
// Generated by scripts/update-pricing-reference.ps1. Data provenance: docs/pricing-reference.md.
static constexpr const char* kBundledPricingDate = "$RetrievedAt";
$liteLiteral
$devLiteral
"@
[IO.File]::WriteAllText((Join-Path $repo 'src/pricing-data.inc'), $content, [Text.UTF8Encoding]::new($false))
foreach ($p in @(@('LICENSE.litellm','LICENSE.pricing-litellm'),@('LICENSE.models-dev','LICENSE.pricing-models-dev'))) {
    Copy-Item -LiteralPath (Join-Path $InputDirectory $p[0]) -Destination (Join-Path $repo ('vendor/'+$p[1]))
}
$manifest = [ordered]@{
    retrievedAt = $RetrievedAt; generation = 'First-party text/code tariffs and selected hosted endpoints; no upstream implementation code copied.'
    litellm = [ordered]@{ url = $feeds['litellm.json']; sha256 = (Get-FileHash (Join-Path $InputDirectory 'litellm.json')).Hash.ToLowerInvariant(); license = 'MIT'; entries = $lite.Count }
    modelsDev = [ordered]@{ url = $feeds['models-dev.json']; sha256 = (Get-FileHash (Join-Path $InputDirectory 'models-dev.json')).Hash.ToLowerInvariant(); license = 'MIT'; entries = ($dev.Values.models.Values | Measure-Object).Count }
    generatedSha256 = (Get-FileHash (Join-Path $repo 'src/pricing-data.inc')).Hash.ToLowerInvariant()
    cursor = [ordered]@{ url = 'https://cursor.com/docs/models-and-pricing'; verifiedAt = '2026-10-09'; entries = 2; description = 'Composer 2.5 standard/fast; manually verified tariff facts in pricing.cpp, cache-write dash remains unknown.' }
}
$manifest | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $repo 'vendor/pricing-sources.json') -Encoding UTF8
Write-Host "Generated pricing-data.inc: $($lite.Count) LiteLLM rows, $(($dev.Values.models.Values | Measure-Object).Count) models.dev rows; $([Text.Encoding]::UTF8.GetByteCount($content)) bytes."
